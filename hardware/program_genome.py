"""Evolve the SWITCH PROGRAM itself.

The genome is a parameterization of a fixed P4 skeleton — every instance
compiles by construction, because the slots are constrained to
type-compatible values. Fitness is the readout error of the RECEIPT
state, measured on the live switch after a hot-swap.

Genome slots:
  op        : the recurrence operation in {mul, add, xor, shift_mul}
  shift     : fixed-point scaling constant (bounded)
  feedback  : which register feeds back into the next packet
  receipt_map : which registers land in which receipt fields

Loop:  generate -> compile (0.22s) -> hot-swap (0.03s) -> inject a
       test signal -> measure the receipt state -> train a ridge
       readout -> fitness = validation NMSE.
"""
